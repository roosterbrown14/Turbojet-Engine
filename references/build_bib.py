UA = {"User-Agent": "turbojet-research (mailto:none@example.org)"}


def fetch(doi):
    for attempt in range(6):
        try:
            req = urllib.request.Request(f"https://api.crossref.org/works/{doi}", headers=UA)
            return json.load(urllib.request.urlopen(req, timeout=30))["message"]
        except urllib.error.HTTPError as e:
            if e.code != 429:
                raise
            time.sleep(5 * (attempt + 1))
    raise RuntimeError(f"Crossref rate limit not cleared for {doi}")


def clean(s):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", s)).strip()


def people(lst):
    seen, out = set(), []
    for a in lst:
        name = f"{a.get('family', '')}, {a.get('given', '')}".strip(", ")
        if a.get("family") in ("al", "", None) or name in seen:
            continue
        seen.add(name)
        out.append(name)
    return " and ".join(out)


def main():
    print("% Generated by references/build_bib.py from Crossref metadata.\n")
    for key, doi in DOIS.items():
        m = fetch(doi)
        time.sleep(1.0)
        authors = people(m.get("author") or m.get("editor") or [])
        title = clean(m["title"][0])
        venue = clean((m.get("container-title") or [""])[0])
        year = m.get("issued", {}).get("date-parts", [[None]])[0][0]
        typ = m.get("type")
        if typ in ("book", "monograph", "edited-book"):
            kind, field, venue = "book", "publisher", m.get("publisher", "")
        elif typ == "proceedings-article":
            kind, field = "inproceedings", "booktitle"
        elif typ == "book-chapter":
            kind, field = "incollection", "booktitle"
        else:
            kind, field = "article", "journal"
        extra = "".join(f",\n  {b} = {{{m[k]}}}" for k, b in (("volume", "volume"), ("page", "pages")) if m.get(k))
        if key in NOTES:
            extra += f",\n  note = {{{NOTES[key]}}}"
        print(f"@{kind}{{{key},\n  author = {{{authors}}},\n  title = {{{title}}},\n"
              f"  {field} = {{{venue}}},\n  year = {{{year}}}{extra},\n  doi = {{{m['DOI']}}}}}\n")
    print(BOOKS)


if __name__ == "__main__":
    main()
